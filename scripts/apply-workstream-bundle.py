#!/usr/bin/env python3
"""Apply or check the workstream protocol bundle (TASK-3953) in a consumer repository.

The source of truth is this repository's own installation of the bundle: the
files in COPIED, skills/<id>/ for the Claude Code skills, the "## Workstream
protocol" section of AGENTS.md, the "## Workstream" section of the PR template,
the workstream-note hooks in .claude/settings.json and the worktree lines in
.gitignore.

Copied files are overwritten. Everything else is only added when missing: an
existing docs/workstreams/README.md (the repo's index), other settings, other
guide text and generated guides are left alone.

Apply prints each path it wrote, one per line, for the caller to `git add`.
--check prints the paths that would change and exits 1 when there are any.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

COPIED = [
    "scripts/workstream-note.mjs",
    "scripts/workstream-note.test.mjs",
    "docs/workstreams/_template.md",
    ".cursor/rules/workstreams.mdc",
    ".cursor/commands/handoff.md",
    ".cursor/commands/resume-workstream.md",
]
SKILLS = ["handoff", "resume-workstream"]
INDEX = "docs/workstreams/README.md"
SETTINGS = ".claude/settings.json"
HOOK_SCRIPT = "scripts/workstream-note.mjs"
WORKTREES = [".worktrees/", ".claude/worktrees/"]
GITIGNORE_HEADER = "# Local worktrees (workstream protocol, TASK-3953)"
PR_TEMPLATES = [
    ".github/pull_request_template.md",
    ".github/PULL_REQUEST_TEMPLATE.md",
    "pull_request_template.md",
    "PULL_REQUEST_TEMPLATE.md",
    "docs/pull_request_template.md",
    "docs/PULL_REQUEST_TEMPLATE.md",
]
SCHEMA = "https://json.schemastore.org/claude-code-settings.json"
AGENTS_STUB = (
    "# AGENTS.md\n\n"
    "Shared guide for agents working in this repository. Codex, Cursor and other agents read "
    "this file directly; Claude Code loads it through `CLAUDE.md`.\n"
)
CLAUDE_STUB = (
    "# CLAUDE.md\n\n"
    "The shared agent guide for this repo is `AGENTS.md`, imported below.\n\n"
    "@AGENTS.md\n"
)
HAS_PROTOCOL = re.compile(r"workstream protocol", re.IGNORECASE)
GENERATED = re.compile(r"do not edit by hand|generated by", re.IGNORECASE)


class BundleError(Exception):
    pass


def files_below(root: Path) -> dict[str, Path]:
    return {p.relative_to(root).as_posix(): p for p in sorted(root.rglob("*")) if p.is_file()}


def section(text: str, heading: str) -> str:
    """Return the "## heading" section of a markdown file, up to the next "## " heading."""
    lines = text.splitlines(keepends=True)
    start = next((i for i, line in enumerate(lines) if line.rstrip() == f"## {heading}"), None)
    if start is None:
        raise BundleError(f"source has no '## {heading}' section")
    end = next((i for i in range(start + 1, len(lines)) if lines[i].startswith("## ")), len(lines))
    return "".join(lines[start:end]).rstrip("\n") + "\n"


def index_seed(text: str) -> str:
    """The index README with its table header kept and its rows dropped."""
    lines = text.splitlines(keepends=True)
    start = next(i for i, line in enumerate(lines) if line.rstrip() == "## Index")
    separator = next(i for i in range(start, len(lines)) if lines[i].startswith("|---"))
    return "".join(lines[: separator + 1])


def appended(text: str, block: str) -> str:
    return text.rstrip("\n") + "\n\n" + block


def is_ignored(consumer: Path, pattern: str) -> bool:
    gitignore = consumer / ".gitignore"
    if gitignore.is_file() and pattern in gitignore.read_text(encoding="utf-8").splitlines():
        return True
    probe = pattern + "probe"
    result = subprocess.run(
        [
            "git",
            "-c",
            "core.excludesFile=",
            "-C",
            str(consumer),
            "check-ignore",
            "-q",
            "--no-index",
            probe,
        ],
        capture_output=True,
        check=False,
    )
    return result.returncode == 0


def workstream_hooks(source: Path) -> dict[str, list[dict]]:
    hooks = json.loads((source / SETTINGS).read_text(encoding="utf-8")).get("hooks", {})
    wanted = {
        event: [
            g
            for g in groups
            if any(HOOK_SCRIPT in h.get("command", "") for h in g.get("hooks", []))
        ]
        for event, groups in hooks.items()
    }
    wanted = {event: groups for event, groups in wanted.items() if groups}
    if not wanted:
        raise BundleError(f"source {SETTINGS} has no {HOOK_SCRIPT} hooks")
    return wanted


def merged_settings(source: Path, consumer: Path) -> str | None:
    path = consumer / SETTINGS
    if path.is_file():
        try:
            settings = json.loads(path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as error:
            raise BundleError(f"{SETTINGS} is not valid JSON: {error}") from error
    else:
        settings = {"$schema": SCHEMA}
    hooks = settings.setdefault("hooks", {})
    if not isinstance(hooks, dict):
        raise BundleError(f"{SETTINGS}: 'hooks' is not an object")
    changed = not path.is_file()
    for event, groups in workstream_hooks(source).items():
        existing = hooks.setdefault(event, [])
        if not any(
            HOOK_SCRIPT in h.get("command", "") for g in existing for h in g.get("hooks", [])
        ):
            existing.extend(groups)
            changed = True
    return json.dumps(settings, indent=2, ensure_ascii=False) + "\n" if changed else None


def plan(source: Path, consumer: Path) -> tuple[dict[str, bytes], list[str]]:
    """Map each consumer path that needs writing to its new content; also return notes."""
    writes: dict[str, bytes] = {}
    notes: list[str] = []

    def want(rel: str, data: bytes | str) -> None:
        data = data.encode("utf-8") if isinstance(data, str) else data
        path = consumer / rel
        if not path.is_file() or path.read_bytes() != data:
            writes[rel] = data

    def read(rel: str) -> str:
        return (consumer / rel).read_text(encoding="utf-8")

    for rel in COPIED:
        want(rel, (source / rel).read_bytes())
    for skill in SKILLS:
        for rel, path in files_below(source / "skills" / skill).items():
            want(f".claude/skills/{skill}/{rel}", path.read_bytes())

    if not (consumer / INDEX).is_file():
        want(INDEX, index_seed((source / INDEX).read_text(encoding="utf-8")))

    settings = merged_settings(source, consumer)
    if settings is not None:
        want(SETTINGS, settings)

    missing = [p for p in WORKTREES if not is_ignored(consumer, p)]
    if missing:
        text = read(".gitignore") if (consumer / ".gitignore").is_file() else ""
        block = GITIGNORE_HEADER + "\n" + "".join(p + "\n" for p in missing)
        want(".gitignore", appended(text, block) if text.strip() else block)

    protocol = section((source / "AGENTS.md").read_text(encoding="utf-8"), "Workstream protocol")
    for rel, stub in (("AGENTS.md", AGENTS_STUB), ("CLAUDE.md", CLAUDE_STUB)):
        if not (consumer / rel).is_file():
            want(rel, appended(stub, protocol) if rel == "AGENTS.md" else stub)
            continue
        text = read(rel)
        if HAS_PROTOCOL.search(text) or (rel == "CLAUDE.md" and "@AGENTS.md" in text.splitlines()):
            continue
        if GENERATED.search(text):
            notes.append(f"{rel} is generated: add the Workstream protocol at its source")
            continue
        want(rel, appended(text, protocol))

    source_template = (source / PR_TEMPLATES[0]).read_text(encoding="utf-8")
    checkbox = section(source_template, "Workstream")
    templates = [rel for rel in PR_TEMPLATES if (consumer / rel).is_file()]
    for rel in templates:
        if not re.search(r"^##\s+Workstream\s*$", read(rel), re.MULTILINE):
            want(rel, appended(read(rel), checkbox))
    if not templates:
        if (consumer / ".github" / "PULL_REQUEST_TEMPLATE").is_dir():
            notes.append(
                ".github/PULL_REQUEST_TEMPLATE/ holds several templates: add the Workstream checkbox by hand"
            )
        else:
            want(PR_TEMPLATES[0], source_template)

    return writes, notes


def run(source: Path, consumer: Path, check: bool) -> int:
    try:
        writes, notes = plan(source, consumer)
    except BundleError as error:
        print(f"workstream bundle: {error}", file=sys.stderr)
        return 2
    for note in notes:
        print(f"note: {note}", file=sys.stderr)
    if check:
        for rel in writes:
            print(f"drift: {rel}", file=sys.stderr)
        if writes:
            print(f"workstream bundle check failed: {len(writes)} path(s) differ", file=sys.stderr)
            return 1
        print("workstream bundle check passed")
        return 0
    for rel, data in writes.items():
        path = consumer / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(data)
        print(rel)
    return 0


def selftest() -> int:
    script = Path(__file__).resolve()
    problems: list[str] = []

    def call(consumer: Path, *args: str) -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            [sys.executable, str(script), "--consumer-root", str(consumer), *args],
            capture_output=True,
            text=True,
            check=False,
        )

    def expect(name: str, ok: bool, result: subprocess.CompletedProcess[str] | None = None) -> None:
        print(f"selftest {name}: {'ok' if ok else 'FAILED'}")
        if not ok:
            problems.append(name)
            if result is not None:
                print(result.stdout, end="")
                print(result.stderr, end="", file=sys.stderr)

    def repo(root: Path, files: dict[str, str]) -> Path:
        root.mkdir(parents=True)
        subprocess.run(["git", "-C", str(root), "init", "-q"], check=True)
        for rel, text in files.items():
            (root / rel).parent.mkdir(parents=True, exist_ok=True)
            (root / rel).write_text(text, encoding="utf-8")
        return root

    with tempfile.TemporaryDirectory() as temp:
        # A repo with none of the bundle gets all of it, then checks clean, then a re-run is a no-op.
        fresh = repo(Path(temp) / "fresh", {"README.md": "x\n"})
        result = call(fresh, "--check")
        expect(
            "FRESH_CHECK_RED",
            result.returncode == 1 and "drift: scripts/workstream-note.mjs" in result.stderr,
            result,
        )
        result = call(fresh)
        written = set(result.stdout.split())
        wanted = {
            *COPIED,
            INDEX,
            SETTINGS,
            ".gitignore",
            "AGENTS.md",
            "CLAUDE.md",
            PR_TEMPLATES[0],
            ".claude/skills/handoff/SKILL.md",
            ".claude/skills/resume-workstream/SKILL.md",
        }
        expect("FRESH_APPLY", result.returncode == 0 and wanted <= written, result)
        result = call(fresh, "--check")
        expect("FRESH_CHECK_GREEN", result.returncode == 0, result)
        result = call(fresh)
        expect("FRESH_REAPPLY_NOOP", result.returncode == 0 and result.stdout == "", result)
        index = (fresh / INDEX).read_text(encoding="utf-8")
        expect("FRESH_INDEX_EMPTY", index.rstrip().endswith("|---|---|---|---|---|---|"))

        # A repo with its own setup keeps it; only the missing pieces are added.
        settings = {
            "permissions": {"allow": ["Bash(ls)"]},
            "hooks": {"SessionEnd": [{"hooks": [{"type": "command", "command": "node x.mjs"}]}]},
        }
        row = "| [mine](mine.md) | V | `claude/mine` | active | — | TASK-1 |\n"
        existing = repo(
            Path(temp) / "existing",
            {
                SETTINGS: json.dumps(settings),
                "AGENTS.md": "# Guide\n\nHouse rules.\n",
                "CLAUDE.md": "# CLAUDE.md\n\n@AGENTS.md\n",
                ".github/PULL_REQUEST_TEMPLATE.md": "## Summary\n",
                ".gitignore": ".claude/\n",
                INDEX: "# Workstreams\n\n## Index\n\n| Workstream |\n|---|\n" + row,
            },
        )
        result = call(existing)
        merged = json.loads((existing / SETTINGS).read_text(encoding="utf-8"))
        expect(
            "EXISTING_SETTINGS_MERGED",
            result.returncode == 0
            and merged["permissions"] == settings["permissions"]
            and merged["hooks"]["SessionEnd"] == settings["hooks"]["SessionEnd"]
            and {"SessionStart", "Stop"} <= merged["hooks"].keys(),
            result,
        )
        agents = (existing / "AGENTS.md").read_text(encoding="utf-8")
        expect(
            "EXISTING_AGENTS_APPENDED",
            agents.startswith("# Guide\n\nHouse rules.\n\n## Workstream protocol\n"),
        )
        expect(
            "EXISTING_CLAUDE_IMPORT_KEPT",
            (existing / "CLAUDE.md").read_text(encoding="utf-8") == "# CLAUDE.md\n\n@AGENTS.md\n",
        )
        template = (existing / ".github/PULL_REQUEST_TEMPLATE.md").read_text(encoding="utf-8")
        expect(
            "EXISTING_TEMPLATE_APPENDED",
            "\n## Workstream\n" in template and not (existing / PR_TEMPLATES[0]).exists(),
        )
        ignore = (existing / ".gitignore").read_text(encoding="utf-8")
        expect(
            "EXISTING_GITIGNORE_ONLY_MISSING",
            ".worktrees/\n" in ignore and ".claude/worktrees/" not in ignore,
        )
        expect("EXISTING_INDEX_KEPT", (existing / INDEX).read_text(encoding="utf-8").endswith(row))
        result = call(existing, "--check")
        expect("EXISTING_CHECK_GREEN", result.returncode == 0, result)

        # A stale copy is drift; a generated guide is never edited.
        generated = "<!-- generated by tool; do not edit by hand -->\n# CLAUDE.md\n"
        stale = repo(Path(temp) / "stale", {"CLAUDE.md": generated, "AGENTS.md": generated})
        call(stale)
        (stale / HOOK_SCRIPT).write_text("// edited\n", encoding="utf-8")
        result = call(stale, "--check")
        expect(
            "STALE_CHECK_RED",
            result.returncode == 1
            and f"drift: {HOOK_SCRIPT}" in result.stderr
            and "generated" in result.stderr,
            result,
        )
        expect(
            "GENERATED_GUIDE_UNTOUCHED",
            (stale / "CLAUDE.md").read_text(encoding="utf-8") == generated,
        )

        # Invalid settings JSON stops the run instead of being overwritten.
        broken = repo(Path(temp) / "broken", {SETTINGS: "{ not json"})
        result = call(broken)
        expect(
            "BROKEN_SETTINGS_EXIT_2",
            result.returncode == 2
            and (broken / SETTINGS).read_text(encoding="utf-8") == "{ not json",
            result,
        )

    if problems:
        print(f"workstream bundle selftest failed: {', '.join(problems)}", file=sys.stderr)
        return 1
    print("workstream bundle selftest passed")
    return 0


def main() -> int:
    repo_root = Path(__file__).resolve().parent.parent
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--source-root", type=Path, default=repo_root)
    parser.add_argument("--consumer-root", type=Path)
    parser.add_argument("--check", action="store_true", help="report drift; write nothing")
    parser.add_argument("--selftest", action="store_true")
    args = parser.parse_args()

    if args.selftest:
        return selftest()
    if args.consumer_root is None:
        parser.error("--consumer-root is required unless --selftest is used")
    return run(args.source_root.resolve(), args.consumer_root.resolve(), args.check)


if __name__ == "__main__":
    sys.exit(main())
